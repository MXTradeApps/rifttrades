-- The RiftTrades card catalog, as it already exists in production.
--
-- This project is shared with FAB Trades, which owns the fab_* tables and the
-- unprefixed user-data tables. This file describes only the objects RiftTrades
-- owns, so a clean local stack has enough to run the app against.
--
-- Every statement is guarded, because this migration is applied to a database
-- where all of these objects are already present.

-- On production the extension already lives in the extensions schema, so this is
-- a no-op there. On a fresh database (staging, local supabase db start, CI) the
-- unqualified form would install it into public, which diverges from production
-- and trips Supabase's "extension in public" advisor.
create extension if not exists pg_trgm with schema extensions;

create table if not exists public.sets (
  group_id   bigint primary key,
  name       text        not null,
  set_number integer,
  updated_at timestamptz not null default now()
);

create table if not exists public.cards (
  id               text primary key,
  product_id       bigint      not null,
  set_id           bigint      not null references public.sets(group_id),
  unique_id        text,
  name             text        not null,
  clean_name       text,
  image_url        text,
  tcgplayer_url    text,
  sub_type_name    text,
  is_foil          boolean     not null default false,
  rarity           text,
  collector_number text,
  is_sealed        boolean     not null default false,
  cardmarket_id    bigint,
  cardmarket_name  text,
  modified_on      timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (product_id, sub_type_name)
);

create index if not exists cards_set_id_idx           on public.cards (set_id);
create index if not exists cards_name_idx             on public.cards (name);
create index if not exists cards_collector_number_idx on public.cards (collector_number);
create index if not exists cards_product_id_idx       on public.cards (product_id);
create index if not exists cards_is_sealed_idx        on public.cards (is_sealed);
create index if not exists cards_name_trgm_idx        on public.cards using gin (name gin_trgm_ops);

create table if not exists public.card_prices (
  card_id        text primary key references public.cards(id),
  tcg_low        numeric,
  tcg_mid        numeric,
  tcg_high       numeric,
  tcg_market     numeric,
  tcg_direct_low numeric,
  cm_avg         numeric,
  cm_low         numeric,
  cm_trend       numeric,
  cm_avg_foil    numeric,
  cm_low_foil    numeric,
  cm_trend_foil  numeric,
  updated_at     timestamptz not null default now()
);

create table if not exists public.price_history (
  id          bigint generated by default as identity primary key,
  card_id     text not null references public.cards(id),
  captured_on date not null default current_date,
  tcg_market  numeric,
  tcg_low     numeric,
  cm_trend    numeric,
  cm_low      numeric,
  unique (card_id, captured_on)
);

create index if not exists price_history_card_id_idx     on public.price_history (card_id);
create index if not exists price_history_captured_on_idx on public.price_history (captured_on);

create table if not exists public.pipeline_runs (
  id                 bigint generated by default as identity primary key,
  started_at         timestamptz not null default now(),
  finished_at        timestamptz,
  status             text        not null default 'running',
  total_sets         integer,
  total_cards        integer,
  cardmarket_matched integer,
  notes              text
);

-- Single-row table driving the in-app update prompt.
create table if not exists public.app_config (
  id                smallint primary key default 1 check (id = 1),
  latest_version    text not null,
  min_version       text,
  android_store_url text,
  ios_store_url     text,
  message           text,
  updated_at        timestamptz not null default now()
);

create or replace view public.cards_with_prices as
  select c.id,
         c.product_id,
         c.set_id,
         c.unique_id,
         c.name,
         c.clean_name,
         c.image_url,
         c.tcgplayer_url,
         c.sub_type_name,
         c.is_foil,
         c.rarity,
         c.collector_number,
         c.is_sealed,
         c.cardmarket_id,
         c.cardmarket_name,
         c.modified_on,
         s.name          as set_name,
         p.tcg_low,
         p.tcg_mid,
         p.tcg_high,
         p.tcg_market,
         p.tcg_direct_low,
         p.cm_avg,
         p.cm_low,
         p.cm_trend,
         p.cm_avg_foil,
         p.cm_low_foil,
         p.cm_trend_foil,
         p.updated_at    as price_updated_at
    from public.cards c
    join public.sets s       on s.group_id = c.set_id
    left join public.card_prices p on p.card_id = c.id;

-- Catalog and prices are public information; both are read without signing in.
-- The pipeline writes with the service role, which bypasses RLS, so no insert or
-- update policy is needed anywhere here.
alter table public.sets          enable row level security;
alter table public.cards         enable row level security;
alter table public.card_prices   enable row level security;
alter table public.price_history enable row level security;
alter table public.app_config    enable row level security;

-- Ingest logs are operational data and no client's business, so this one gets
-- RLS with no policy at all: service role only.
alter table public.pipeline_runs enable row level security;

drop policy if exists "Public read sets"          on public.sets;
drop policy if exists "Public read cards"         on public.cards;
drop policy if exists "Public read card_prices"   on public.card_prices;
drop policy if exists "Public read price_history" on public.price_history;
drop policy if exists "Public read app_config"    on public.app_config;

create policy "Public read sets"          on public.sets          for select to anon, authenticated using (true);
create policy "Public read cards"         on public.cards         for select to anon, authenticated using (true);
create policy "Public read card_prices"   on public.card_prices   for select to anon, authenticated using (true);
create policy "Public read price_history" on public.price_history for select to anon, authenticated using (true);
create policy "Public read app_config"    on public.app_config    for select to anon, authenticated using (true);

grant select on public.sets, public.cards, public.card_prices,
               public.price_history, public.app_config,
               public.cards_with_prices
  to anon, authenticated;
